def mall_error_reply(kind: str, http_status: int | None, code: int | None) -> str:
    """多个商品节点共用明确的上游失败话术，不使用上游自由文本。"""
    if http_status == 429 or code == 429:
        return "商城查询暂时受到限流，本次未完成，请稍后再试。"
    if http_status == 404 or code == 404:
        return "本次查询的商品已无法获取，请重新选择商品。"
    if kind == "response":
        return "商城返回的资料格式暂时无法处理，本次查询未完成，请稍后再试。"
    return "商城商品查询暂不可用，本次未完成查询，请稍后再试。"
